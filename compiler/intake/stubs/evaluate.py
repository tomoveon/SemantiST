"""Held-out evaluation of stub generation against real implementations.

A library whose dependency closure is in the corpus (OSCAT building and
network use OSCAT basic) is treated as if the dependency were missing: the
names it takes from the dependency become gaps, stubs are generated by the
same prompt and cache as :mod:`.generate` (the real declarations are not
shown), and the result is compared with the dependency:

1. **signature**: kind, result type, and the inputs/outputs (names, types,
   order) of the stub against the real declaration;
2. **build retention**: of the library's POUs that type check with the real
   dependency, how many type check with the stubs instead;
3. **behaviour** of stubs with a body (category ``pure``): both functions are
   called on the same seeded random inputs and the results compared.

    python3 -m compiler.intake.stubs.evaluate --libraries artifacts/intake/libraries \\
        --library 02_CODESYS23/native_oscat_building_100 --library 02_CODESYS23/native_oscat_network_100 \\
        --work artifacts/intake/stubs-eval
"""

from __future__ import annotations

import argparse
import collections
import json
import random
import re
import shutil
import subprocess
from pathlib import Path

from compiler.parser.st import significant, tokenize_lossless

from ..structure import split_units
from .docs import find as find_passages
from .gaps import collect
from .generate import IMAGE, ROOT, _ask
from .llm import ClaudeCLI

ELEMENTARY = {"BOOL", "SINT", "INT", "DINT", "LINT", "USINT", "UINT", "UDINT", "ULINT", "BYTE", "WORD", "DWORD",
              "LWORD", "REAL", "LREAL"}


def interface(text: str) -> dict[str, dict]:
    """Kind, result type and parameters of every POU and type in ``text``."""
    result = {}
    lossless = tokenize_lossless(text)
    tokens = significant(lossless)
    for unit in split_units(text, lossless):
        if unit.kind not in {"FUNCTION", "FUNCTION_BLOCK", "TYPE"} or not unit.name:
            continue
        body = [t for t in tokens if unit.start <= t.start < unit.end]
        entry = {"kind": unit.kind, "result": None, "params": []}
        if unit.kind == "FUNCTION" and len(body) > 3 and body[2].text == ":":
            entry["result"] = _norm(body[3].text)
        block = None
        for i, token in enumerate(body):
            if token.upper in {"VAR_INPUT", "VAR_OUTPUT", "VAR_IN_OUT"}:
                block = token.upper
            elif token.upper in {"END_VAR", "VAR", "VAR_TEMP"}:
                block = None
            elif block and token.kind in {"identifier", "keyword"} and i + 2 < len(body) and body[i + 1].text == ":" \
                    and body[i - 1].text in {";", block, "VAR_INPUT", "VAR_OUTPUT", "VAR_IN_OUT"}:
                entry["params"].append((block, token.upper, _norm(body[i + 2].text)))
        result[unit.name.upper()] = entry
    return result


def _norm(type_name: str) -> str:
    return re.sub(r"\(", "[", re.sub(r"\)", "]", type_name.upper()))


def compare(stub: dict, real: dict) -> dict:
    inputs = lambda e: [(n, t) for b, n, t in e["params"] if b != "VAR_OUTPUT"]
    outputs = lambda e: {(n, t) for b, n, t in e["params"] if b == "VAR_OUTPUT"}
    return {
        "kind": stub["kind"] == real["kind"],
        "result": stub["result"] == real["result"],
        "input_names": [n for n, _ in inputs(stub)] == [n for n, _ in inputs(real)],
        "input_types": [t for _, t in inputs(stub)] == [t for _, t in inputs(real)],
        "outputs": outputs(stub) <= outputs(real),
        "exact": stub["kind"] == real["kind"] and stub["result"] == real["result"]
        and inputs(stub) == inputs(real) and outputs(stub) <= outputs(real),
    }


def has_statements(declaration: str) -> bool:
    """Whether a function declaration has statements after its last END_VAR."""
    return bool(re.search(r"(?is)END_VAR\s*(\S.*?)\s*END_FUNCTION\b", declaration))


def _random_literal(type_name: str, rng: random.Random) -> str:
    if type_name == "BOOL":
        return rng.choice(["TRUE", "FALSE"])
    if type_name in {"REAL", "LREAL"}:
        return f"{type_name}#{rng.uniform(-1000, 1000):.3f}"
    bits = {"SINT": 8, "USINT": 8, "BYTE": 8, "INT": 16, "UINT": 16, "WORD": 16, "DINT": 32, "UDINT": 32,
            "DWORD": 32, "LINT": 64, "ULINT": 64, "LWORD": 64}[type_name]
    signed = type_name in {"SINT", "INT", "DINT", "LINT"}
    value = rng.randrange(-(1 << (bits - 1)), 1 << (bits - 1)) if signed else rng.randrange(0, 1 << bits)
    return f"{type_name}#{value}"


def behaviour_program(name: str, real: dict, stub_text: str, samples: int, seed: int) -> str | None:
    """A main program printing real and stub results on the same inputs, or
    None when the function is not elementary in and out."""
    inputs = [(n, t) for b, n, t in real["params"] if b == "VAR_INPUT"]
    if real["kind"] != "FUNCTION" or real["result"] not in ELEMENTARY or any(b != "VAR_INPUT" for b, _, _ in real["params"]) \
            or any(t not in ELEMENTARY for _, t in inputs):
        return None
    rng = random.Random(f"{seed}:{name}")
    renamed = re.sub(rf"\b{re.escape(name)}\b", f"{name}__STUB", stub_text, flags=re.I)
    fmt = "%f" if real["result"] in {"REAL", "LREAL"} else "%lld"
    calls = []
    for _ in range(samples):
        args = ", ".join(_random_literal(t, rng) for _, t in inputs)
        cast = "LREAL" if real["result"] in {"REAL", "LREAL"} else "LINT"
        calls.append(f"printf('{fmt} {fmt}$N', TO_{cast}({name}({args})), TO_{cast}({name}__STUB({args})));")
    return renamed + "\n\nFUNCTION main : DINT\n" + "\n".join(calls) + "\nmain := 0;\nEND_FUNCTION\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--libraries", type=Path, required=True)
    parser.add_argument("--library", action="append", required=True)
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--budget", type=float, default=10.0)
    parser.add_argument("--samples", type=int, default=20)
    args = parser.parse_args(argv)
    work = args.work.resolve()
    work.mkdir(parents=True, exist_ok=True)
    llm = ClaudeCLI(ROOT / "artifacts/intake/stubs/llm-cache", budget_usd=args.budget)
    rows, programs, build_jobs = [], {}, []
    # The intake report of a library covers its own file.  Resolve a dependency
    # by its normalized relative path and bytes; source digests remain report
    # provenance and are not used as an identity or gate.
    source_reports = []
    for path in sorted(args.libraries.resolve().rglob("compatibility-report.json")):
        report = json.loads(path.read_text(encoding="utf-8"))
        source_reports.append((path.parent, report))
    for library in args.library:
        directory = (args.libraries / library).resolve()
        report = json.loads((directory / "compatibility-report.json").read_text(encoding="utf-8"))
        meta = json.loads((directory / "compatibility.json").read_text(encoding="utf-8"))
        main_file = report["target_identity"]["source"]["file"]
        dependency_files = [d["file"] for d in report["target_identity"].get("dependency_files", [])]
        dependency_accepted = {}
        for dependency in report["target_identity"].get("dependency_files", []):
            name = dependency["file"]
            local_path = directory / "normalized" / name
            if not local_path.is_file():
                continue
            for owner_dir, owner_report in source_reports:
                owner_path = owner_dir / "normalized" / name
                try:
                    same_text = owner_path.is_file() and owner_path.read_bytes() == local_path.read_bytes()
                except OSError:
                    same_text = False
                if same_text:
                    dependency_accepted[name] = sorted(
                        u["line"] for u in owner_report["units"]
                        if u["accepted"] and u["file"] == name
                    )
                    break
        normalized_dir = directory / "normalized"
        texts = {p.relative_to(normalized_dir).as_posix(): p.read_text(encoding="utf-8")
                 for p in sorted(normalized_dir.rglob("*.st"))}
        real = {}
        for name in dependency_files:
            real.update(interface(texts[name]))
        own = interface(texts[main_file])
        used = {t.upper for t in significant(tokenize_lossless(texts[main_file])) if t.is_word}
        held_out = sorted(n for n in real if n in used and n not in own)
        # A copy of the intake result without the dependency: the held-out names are its gaps.
        fake = work / library
        if fake.exists():
            shutil.rmtree(fake)
        (fake / "normalized").mkdir(parents=True)
        fake_source = fake / "normalized" / main_file
        fake_source.parent.mkdir(parents=True, exist_ok=True)
        fake_source.write_text(texts[main_file], encoding="utf-8")
        (fake / "dependency-report.json").write_text(json.dumps({"classifications": {"unresolved": held_out}}),
                                                     encoding="utf-8")
        gaps = collect([(meta["dialect"], library, fake)])
        names = collections.defaultdict(set)
        for gap in gaps.values():
            names[gap.family].add(gap.name)
        passages = find_passages(names)
        stubs = {}
        items = sorted(gaps.values(), key=lambda g: g.key)
        for i in range(0, len(items), 20):
            stubs.update(_ask(llm, meta["dialect"], items[i:i + 20], passages))
        for key, entry in sorted(stubs.items()):
            name = key.split(":", 1)[1]
            generated = interface(entry["declaration"]).get(name)
            row = {"library": library, "name": name, "category": entry["category"], "evidence": entry["evidence"],
                   "passages": len(passages.get((meta["dialect"], name), [])), "parsed": generated is not None}
            if generated is not None and name in real:
                row.update(compare(generated, real[name]))
                has_body = entry["category"] == "pure" and has_statements(entry["declaration"])
                program = behaviour_program(name, real[name], entry["declaration"], args.samples, 7) \
                    if has_body else None
                if program:
                    programs[f"{library}:{name}"] = program
            rows.append(row)
        build_jobs.append({"library": library, "dir": str(directory.relative_to(ROOT)), "main": main_file,
                           "dependency_accepted": dependency_accepted, "stubs": "\n\n".join(e["declaration"] for _, e in sorted(stubs.items()))})
    request = work / "check-request.json"
    request.write_text(json.dumps({"builds": build_jobs, "programs": programs}, ensure_ascii=False), encoding="utf-8")
    subprocess.run(["podman", "run", "--rm", "-v", f"{ROOT}:/src:Z", "-w", "/src", IMAGE, "python3", "-m",
                    "compiler.intake.stubs.evaluate_check", str(request.relative_to(ROOT)),
                    str((work / "check-result.json").relative_to(ROOT))], check=True)
    checked = json.loads((work / "check-result.json").read_text(encoding="utf-8"))
    signature = [r for r in rows if "exact" in r]
    metrics = {k: sum(1 for r in signature if r[k]) for k in ("kind", "result", "input_names", "input_types",
                                                                  "outputs", "exact")}
    behaviour = checked["programs"]
    summary = {
        "libraries": args.library, "held_out_names": len(rows), "compared": len(signature),
        "signature": {k: f"{v}/{len(signature)}" for k, v in metrics.items()},
        "by_evidence": dict(collections.Counter(r["evidence"] for r in rows)),
        "build_retention": checked["builds"],
        "behaviour": {"functions": len(behaviour),
                      "ran": sum(1 for b in behaviour.values() if b.get("samples")),
                      "all_samples_agree": sum(1 for b in behaviour.values()
                                               if b.get("samples") and b["agree"] == b["samples"]),
                      "errors": sum(1 for b in behaviour.values() if "error" in b),
                      "details": behaviour},
        "llm": {"calls": llm.calls, "cache_hits": llm.cache_hits, "cost_usd": round(llm.spent_usd, 4)},
        "rows": rows,
    }
    (work / "evaluation.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in summary.items() if k not in {"rows", "behaviour"}}, indent=1))
    print(json.dumps({k: v for k, v in summary["behaviour"].items() if k != "details"}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

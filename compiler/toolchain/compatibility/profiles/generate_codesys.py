#!/usr/bin/env python3
"""Generate the CODESYS conversion adapter profiles from the pinned RuSTy stdlib.

``codesys-time`` converts between CODESYS temporal units (TIME and TOD in
milliseconds, DATE and DT in seconds since 1970-01-01) and numbers. RuSTy
stores every temporal value as signed 64-bit nanoseconds, so each adapter
changes the unit explicitly. Where RuSTy already defines a conversion of the
same name with nanosecond semantics (TIME_TO_LWORD, ULINT_TO_TIME, ...), the
adapter is named ``__CDS_<name>`` and the profile lists it under ``rebind``:
the normalizer binds the library's calls to the adapter, because the
library means the CODESYS unit.

``codesys-conversions`` provides the CODESYS numeric, BOOL and STRING
conversions the pinned RuSTy does not define, composed from RuSTy primitives.

Only conversions RuSTy lacks (or defines with a different unit) are generated;
no standard-library symbol is redefined. The output is deterministic and
checked in; a test regenerates it against the pinned stdlib.

Usage: generate_codesys.py --stdlib DIR [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

INTEGERS = ["BYTE", "WORD", "DWORD", "LWORD", "SINT", "USINT", "INT", "UINT", "DINT", "UDINT", "LINT", "ULINT"]
SIGNED = {"SINT", "INT", "DINT", "LINT"}
REALS = ["REAL", "LREAL"]
NUMERIC = ["BOOL", *INTEGERS, *REALS]
# CODESYS name -> (RuSTy type, nanoseconds per vendor unit)
TEMPORAL = {
    "TIME": ("TIME", 1_000_000),
    "TOD": ("TIME_OF_DAY", 1_000_000),
    "DATE": ("DATE", 1_000_000_000),
    "DT": ("DATE_AND_TIME", 1_000_000_000),
}
# Conversions between temporal types that keep the value (RuSTy: same nanoseconds).
TEMPORAL_IDENTITY = [("TOD", "TIME"), ("TIME", "TOD"), ("DATE", "DT")]

HEADER = """(* Generated by compiler/toolchain/compatibility/profiles/generate_codesys.py
   from the pinned RuSTy standard library. Do not edit by hand.
{body} *)
"""


def stdlib_functions(stdlib: Path) -> set[str]:
    names: set[str] = set()
    for path in sorted(stdlib.glob("*.st")):
        names.update(m.upper() for m in re.findall(r"(?im)^\s*FUNCTION\s+(\w+)", path.read_text(encoding="utf-8")))
    return names


def function(name: str, result: str, argument: str, body: str, local: str | None = None) -> str:
    lines = [f"FUNCTION {name} : {result}", f"VAR_INPUT IN : {argument}; END_VAR"]
    if local:
        lines.append(f"VAR {local} END_VAR")
    lines.extend("    " + line for line in body.strip().splitlines())
    lines.append("END_FUNCTION")
    return "\n".join(lines) + "\n"


def narrow_from_lint(target: str, expression: str, std: set[str]) -> str:
    """Assign a LINT expression to ``target``, keeping its low bits."""
    if target == "LINT":
        return expression
    if f"LINT_TO_{target}" in std:
        return f"LINT_TO_{target}({expression})"
    raise ValueError(f"no LINT_TO_{target} in the pinned stdlib")


def temporal_adapters(std: set[str]) -> tuple[str, dict[str, str], list[str]]:
    out: list[str] = []
    rebind: dict[str, str] = {}
    generated: list[str] = []

    def emit(vendor_name: str, text_for) -> None:
        name = vendor_name
        if vendor_name in std:
            name = "__CDS_" + vendor_name
            rebind[vendor_name] = name
        text = text_for(name)
        if re.search(rf"\b{re.escape(name)}\s*\(", text):
            raise ValueError(f"{name} would call itself")
        out.append(text)
        generated.append(name)

    def lint_to(vendor: str, expression: str) -> str:
        """``expression`` (LINT, RuSTy's unit) as ``vendor`` using only stdlib functions."""
        if f"LINT_TO_{vendor}" in std:
            return f"LINT_TO_{vendor}({expression})"
        if f"ULINT_TO_{vendor}" in std and "LINT_TO_ULINT" in std:
            # Same 64-bit pattern: RuSTy's ULINT_TO_<temporal> copies the value.
            return f"ULINT_TO_{vendor}(LINT_TO_ULINT({expression}))"
        raise ValueError(f"pinned stdlib has no conversion from LINT to {vendor}")

    for vendor, (rusty_type, factor) in TEMPORAL.items():
        to_lint = f"{vendor}_TO_LINT" if f"{vendor}_TO_LINT" in std else None
        if to_lint is None:
            raise ValueError(f"pinned stdlib lacks {vendor}_TO_LINT")
        units = f"{to_lint}(IN) / LINT#{factor}"
        for target in INTEGERS:
            emit(f"{vendor}_TO_{target}", lambda name, target=target: function(
                name, target, rusty_type, f"{name} := {narrow_from_lint(target, units, std)};"))
        for target in REALS:
            emit(f"{vendor}_TO_{target}", lambda name, target=target: function(
                name, target, rusty_type, f"{name} := LINT_TO_{target}({units});"))
        emit(f"{vendor}_TO_BOOL", lambda name: function(name, "BOOL", rusty_type, f"{name} := {to_lint}(IN) <> 0;"))
        for source in INTEGERS:
            emit(f"{source}_TO_{vendor}", lambda name, source=source: function(
                name, rusty_type, source, f"v := IN;\n{name} := {lint_to(vendor, f'v * LINT#{factor}')};",
                "v : LINT;"))
        for source in REALS:
            # Rounded to whole vendor units (CODESYS: "cast to ULINT and then returned in ms").
            emit(f"{source}_TO_{vendor}", lambda name, source=source: function(
                name, rusty_type, source,
                f"v := {source}_TO_LINT(IN);\n{name} := {lint_to(vendor, f'v * LINT#{factor}')};", "v : LINT;"))
        emit(f"BOOL_TO_{vendor}", lambda name: function(
            name, rusty_type, "BOOL", f"IF IN THEN\n    {name} := {lint_to(vendor, f'LINT#{factor}')};\nELSE\n"
                                     f"    {name} := {lint_to(vendor, 'LINT#0')};\nEND_IF;"))
    for source, target in TEMPORAL_IDENTITY:
        emit(f"{source}_TO_{target}", lambda name, source=source, target=target: function(
            name, TEMPORAL[target][0], TEMPORAL[source][0], f"{name} := {lint_to(target, f'{source}_TO_LINT(IN)')};"))
    return "\n".join(out), rebind, generated


# RuSTy implements these as bit-pattern copies (IEC 61131-3 3rd edition binary
# transfer); CODESYS lists them under "Conversion: Integer", which converts the
# integer value. Their CODESYS adapters are rebound.
RUSTY_BIT_COPIES = {"DWORD_TO_REAL": ("DWORD", "REAL"), "LWORD_TO_LREAL": ("LWORD", "LREAL"),
                    "REAL_TO_DWORD": ("REAL", "DWORD"), "LREAL_TO_LWORD": ("LREAL", "LWORD")}


def bit_copy_adapters(std: set[str]) -> tuple[str, dict[str, str], list[str]]:
    out, rebind, names = [], {}, []
    for vendor, (source, target) in sorted(RUSTY_BIT_COPIES.items()):
        if vendor not in std:
            continue
        name = "__CDS_" + vendor
        rebind[vendor] = name
        if source in REALS:
            body = f"v := {source}_TO_LINT(IN);\n{name} := {narrow_from_lint(target, 'v', std)};"
            out.append(function(name, target, source, body, "v : LINT;"))
        else:
            wide = "ULINT"
            out.append(function(name, target, source, f"v := IN;\n{name} := {wide}_TO_{target}(v);",
                                f"v : {wide};"))
        names.append(name)
    return "\n".join(out), rebind, names


def numeric_adapters(std: set[str]) -> tuple[str, list[str]]:
    out: list[str] = []
    generated: list[str] = []

    def emit(name: str, text: str) -> None:
        if name in std:
            return
        out.append(text)
        generated.append(name)

    for source in NUMERIC:
        for target in NUMERIC:
            if source == target:
                continue
            name = f"{source}_TO_{target}"
            if source == "BOOL":
                one, zero = ("1.0", "0.0") if target in REALS else ("1", "0")
                emit(name, function(name, target, source,
                                    f"IF IN THEN\n    {name} := {one};\nELSE\n    {name} := {zero};\nEND_IF;"))
            elif target == "BOOL":
                zero = "0.0" if source in REALS else "0"
                emit(name, function(name, target, source, f"{name} := IN <> {zero};"))
            elif source in REALS and target in INTEGERS:
                # Rounded like RuSTy's REAL_TO_LINT (half away from zero, as CODESYS),
                # then the low bits are kept.
                emit(name, function(name, target, source,
                                    f"v := {source}_TO_LINT(IN);\n{name} := {narrow_from_lint(target, 'v', std)};",
                                    "v : LINT;"))
            else:
                # Integer to integer or REAL: RuSTy converts by the source's signedness,
                # truncating to the target width like CODESYS.
                emit(name, function(name, target, source, f"{name} := IN;"))
    for source in [*INTEGERS, "BOOL"]:
        name = f"{source}_TO_STRING"
        if source == "BOOL":
            emit(name, function(name, "STRING", source,
                                f"IF IN THEN\n    {name} := 'TRUE';\nELSE\n    {name} := 'FALSE';\nEND_IF;"))
        else:
            wide = "LINT" if source in SIGNED else "ULINT"
            emit(name, function(name, "STRING", source, f"v := IN;\n{name} := {wide}_TO_STRING(v);", f"v : {wide};"))
    for target in INTEGERS:
        name = f"STRING_TO_{target}"
        emit(name, function(name, target, "STRING",
                            f"{name} := {narrow_from_lint(target, 'STRING_TO_LINT(IN)', std)};"))
    return "\n".join(out), generated


TIME_NOTE = """   CODESYS TIME and TOD are 32-bit milliseconds, DATE and DT 32-bit seconds
   since 1970-01-01; RuSTy uses signed 64-bit nanoseconds. Adapters divide or
   multiply by the unit and keep the low bits on narrowing, as CODESYS does for
   integer conversions. TIME wrap-around at 2^32 ms is not simulated."""
NUMERIC_NOTE = """   CODESYS conversions the pinned RuSTy lacks, composed from RuSTy
   conversions with CODESYS semantics (low bits kept on narrowing, REAL
   rounded half away from zero, BOOL TRUE = 1)."""


def render(stdlib: Path) -> dict[Path, str]:
    std = stdlib_functions(stdlib)
    time_text, rebind, time_names = temporal_adapters(std)
    numeric_text, numeric_names = numeric_adapters(std | set(time_names) | set(rebind))
    copy_text, copy_rebind, copy_names = bit_copy_adapters(std)
    numeric_text += "\n" + copy_text
    numeric_names += copy_names
    files = {
        HERE / "codesys-time" / "conversions.st": HEADER.format(body=TIME_NOTE) + "\n" + time_text,
        HERE / "codesys-conversions" / "conversions.st": HEADER.format(body=NUMERIC_NOTE) + "\n" + numeric_text,
    }
    time_profile = {
        "schema_version": "semantist.compatibility-profile/1.0.0",
        "name": "codesys-time",
        "dialects": ["codesys"],
        "kind": "semantic_adapter",
        "st_sources": ["conversions.st"],
        "native_sources": [],
        "native_compile_args": [],
        "link_args": [],
        "provides": sorted(time_names),
        "rebind": dict(sorted(rebind.items())),
        "evidence": [
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_time_to.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_date_to.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_real_to.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_convert_integer.html",
        ],
        "assumptions": [
            "TIME/TOD are whole milliseconds and DATE/DT whole seconds; sub-unit nanoseconds are discarded by the "
            "vendor-unit conversions.",
            "TIME wrap-around at 2^32 ms is not simulated: values outside 0..2^32-1 ms keep their 64-bit value; "
            "conversions to 32-bit integers still yield the vendor's low 32 bits.",
            "Negative integers converted to TIME give negative durations (CODESYS TIME is unsigned).",
        ],
    }
    numeric_profile = {
        "schema_version": "semantist.compatibility-profile/1.0.0",
        "name": "codesys-conversions",
        "dialects": ["codesys"],
        "kind": "semantic_adapter",
        "st_sources": ["conversions.st"],
        "native_sources": [],
        "native_compile_args": [],
        "link_args": [],
        "provides": sorted(numeric_names),
        "rebind": dict(sorted(copy_rebind.items())),
        "evidence": [
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_convert_integer.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_real_to.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_bool_to.html",
            "rusty_compatibility/01_CODESYS3/该厂商st规范/ST规范/CODESYS3_Programming_Reference/_cds_operator_string_to.html",
        ],
        "assumptions": [
            "STRING_TO_<integer> handles decimal strings like RuSTy's STRING_TO_LINT; CODESYS also accepts "
            "type-prefixed literals ('16#FF') and grouping underscores, which are not claimed equivalent.",
            "REAL to unsigned integers outside the target range: CODESYS converts through UDINT/ULINT; the result "
            "for negative or too large values is not claimed equivalent.",
            "Integer to BOOL: the generated adapters return TRUE for non-zero values (CODESYS documents this for "
            "TIME_TO_BOOL and REAL_TO_BOOL). RuSTy's own BYTE/WORD/DWORD/LWORD_TO_BOOL return the least "
            "significant bit; they are not rebound, and their uses are reported as unverified.",
            "DWORD_TO_REAL, LWORD_TO_LREAL, REAL_TO_DWORD and LREAL_TO_LWORD convert the value (CODESYS "
            "'Conversion: Integer'); RuSTy copies the bit pattern, so library calls are rebound to the adapters.",
        ],
    }
    files[HERE / "codesys-time" / "profile.json"] = json.dumps(time_profile, ensure_ascii=False, indent=2) + "\n"
    files[HERE / "codesys-conversions" / "profile.json"] = json.dumps(numeric_profile, ensure_ascii=False,
                                                                      indent=2) + "\n"
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--stdlib", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="fail when the checked-in files differ")
    args = parser.parse_args(argv)
    stale = []
    for path, text in render(args.stdlib).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated profiles: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Run selected SemantiST ablations independently; leave interpretation offline."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from experiments.ablations.run_ablation import main as run_ablation_main  # noqa: E402
from experiments.comparison.ablations import ABLATION_PROFILES  # noqa: E402


def suite_arguments(argv: list[str]) -> tuple[str, list[str], list[str]]:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--run-prefix", required=True)
    parser.add_argument(
        "--variants",
        default=",".join(ABLATION_PROFILES),
        help="comma-separated profiles; default is full plus all ablations",
    )
    args, remaining = parser.parse_known_args(argv)
    variants = [item.strip() for item in args.variants.split(",") if item.strip()]
    if not variants or len(set(variants)) != len(variants):
        parser.error("--variants must contain distinct profile names")
    unknown = [item for item in variants if item not in ABLATION_PROFILES]
    if unknown:
        parser.error(f"unknown ablation profiles: {', '.join(unknown)}")
    if not args.run_prefix or any(char in args.run_prefix for char in "/\\:|"):
        parser.error("--run-prefix must be a directory-name prefix")
    if any(value.split("=", 1)[0] in {"--run-id", "--variant"} for value in remaining):
        parser.error("run IDs and profiles are generated by the suite")
    return args.run_prefix, variants, remaining


def main(argv: list[str] | None = None) -> int:
    prefix, variants, forwarded = suite_arguments(sys.argv[1:] if argv is None else argv)
    for variant in variants:
        run_id = f"{prefix}_{variant}"
        print(f"[ablation] {variant}: {run_id}", flush=True)
        result = run_ablation_main(
            ["--variant", variant, "--run-id", run_id, *forwarded]
        )
        if result != 0:
            return result
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

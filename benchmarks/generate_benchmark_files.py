#!/usr/bin/env python3
"""Generate program.st and structuredfuzzer.st for all 90 benchmark targets.

Usage:
    python3 benchmarks/generate_benchmark_files.py [--suite SUITE] [--id ID] [--dry-run]

Writes, next to each existing target.st:
    program.st          RuSTy PLC_PRG wrapper
    structuredfuzzer.st matiec-compatible standalone ST

The precise harness.c is generated by a separate pass (it needs the RuSTy LLVM
IR); see benchmarks/check_benchmark_files.py.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from benchmarks.lib.generator import (
    ROOT,
    build_program_st,
    build_structuredfuzzer_st,
    load_targets,
)
from benchmarks.lib.st_extract import extract_pou_text, extract_signature


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--suite", action="append", default=[])
    parser.add_argument("--id", action="append", default=[])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    targets = load_targets()
    if args.suite:
        targets = [t for t in targets if t.suite in args.suite]
    if args.id:
        targets = [t for t in targets if t.id in args.id or t.function in args.id]

    report: dict[str, object] = {"targets": []}
    failures = 0
    for t in targets:
        entry: dict[str, object] = {
            "suite": t.suite,
            "id": t.id,
            "function": t.function,
            "kind": t.kind,
            "target_sha256": sha256(Path(t.st_file)),
        }
        try:
            sig = extract_signature(t.st_file, t.function)
            pou_text = extract_pou_text(t.st_file, t.function)
            program_st = build_program_st(sig)
            sf_st, unresolved = build_structuredfuzzer_st(t.directory, sig, pou_text, t.suite)
            entry["program_st"] = "ok"
            entry["structuredfuzzer_st"] = "ok" if not unresolved else "unresolved"
            entry["unresolved_deps"] = unresolved
            if not args.dry_run:
                (t.directory / "program.st").write_text(program_st, encoding="utf-8")
                (t.directory / "structuredfuzzer.st").write_text(sf_st, encoding="utf-8")
        except Exception as exc:  # noqa: BLE001
            failures += 1
            entry["error"] = str(exc)
            entry["program_st"] = "error"
            entry["structuredfuzzer_st"] = "error"

        report["targets"].append(entry)
        status = entry.get("program_st", "?")
        print(f"[gen] {t.suite}::{t.id} program.st={status} sf_st={entry.get('structuredfuzzer_st')}", flush=True)

    out = ROOT / "artifacts" / "benchmarks" / "generation-report.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"[gen] wrote {out}")
    print(f"[gen] total={len(targets)} failures={failures}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
